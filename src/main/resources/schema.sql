CREATE TABLE IF NOT EXISTS app_users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 100) PRIMARY KEY,
    username VARCHAR(100) NOT NULL CHECK (LENGTH(TRIM(username)) > 0),
    email VARCHAR(255),
    created_at TIMESTAMP NOT NULL
);

CREATE TABLE IF NOT EXISTS surveys (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 100) PRIMARY KEY,
    title VARCHAR(255) NOT NULL CHECK (LENGTH(TRIM(title)) > 0),
    author_id BIGINT NOT NULL REFERENCES app_users(id) ON DELETE CASCADE,
    start_date TIMESTAMP,
    end_date TIMESTAMP,
    status VARCHAR(32) NOT NULL CHECK (status IN ('DRAFT', 'ACTIVE', 'CLOSED')),
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    CHECK (start_date IS NULL OR end_date IS NULL OR end_date > start_date),
    CHECK (status = 'DRAFT' OR (start_date IS NOT NULL AND end_date IS NOT NULL))
);

CREATE TABLE IF NOT EXISTS survey_questions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 100) PRIMARY KEY,
    survey_id BIGINT NOT NULL REFERENCES surveys(id) ON DELETE CASCADE,
    text VARCHAR(2000) NOT NULL CHECK (LENGTH(TRIM(text)) > 0),
    required BOOLEAN NOT NULL,
    UNIQUE (id, survey_id)
);

CREATE TABLE IF NOT EXISTS survey_question_options (
    question_id BIGINT NOT NULL REFERENCES survey_questions(id) ON DELETE CASCADE,
    option_order INTEGER NOT NULL CHECK (option_order >= 0),
    option_value VARCHAR(1000) NOT NULL CHECK (LENGTH(TRIM(option_value)) > 0),
    PRIMARY KEY (question_id, option_order),
    UNIQUE (question_id, option_value)
);

CREATE TABLE IF NOT EXISTS survey_participations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 100) PRIMARY KEY,
    survey_id BIGINT NOT NULL REFERENCES surveys(id) ON DELETE CASCADE,
    respondent_id BIGINT NOT NULL REFERENCES app_users(id) ON DELETE CASCADE,
    status VARCHAR(32) NOT NULL CHECK (status IN ('IN_PROGRESS', 'SUBMITTED', 'CANCELED')),
    created_at TIMESTAMP NOT NULL,
    submitted_at TIMESTAMP,
    UNIQUE (survey_id, respondent_id),
    UNIQUE (id, survey_id),
    CHECK (CASE WHEN status = 'SUBMITTED' THEN submitted_at IS NOT NULL ELSE submitted_at IS NULL END)
);

CREATE TABLE IF NOT EXISTS survey_answers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 100) PRIMARY KEY,
    survey_id BIGINT NOT NULL,
    participation_id BIGINT NOT NULL,
    question_id BIGINT NOT NULL,
    selected_value VARCHAR(1000) NOT NULL CHECK (LENGTH(TRIM(selected_value)) > 0),
    UNIQUE (participation_id, question_id),
    FOREIGN KEY (participation_id, survey_id) REFERENCES survey_participations(id, survey_id) ON DELETE CASCADE,
    FOREIGN KEY (question_id, survey_id) REFERENCES survey_questions(id, survey_id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_surveys_author ON surveys(author_id);
CREATE INDEX IF NOT EXISTS idx_questions_survey ON survey_questions(survey_id);
CREATE INDEX IF NOT EXISTS idx_participations_respondent ON survey_participations(respondent_id);
CREATE INDEX IF NOT EXISTS idx_answers_question ON survey_answers(question_id);
